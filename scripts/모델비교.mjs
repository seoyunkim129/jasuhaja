// data/수정안/<모델>.json(수정안만들기.mjs가 만든 것)을 모아 모델별 표를 만든다.
// 기준은 지금 자유수영시간.csv다. CSV도 틀릴 수 있어서 "정답률"이 아니라 "CSV와의 일치율"이라고 부른다.
//
// 실행: node scripts/모델비교.mjs claude gemini
// 결과: data/비교/결과.md
import fs from 'node:fs';

const 모델들 = process.argv.slice(2);
const 퍼센트 = (a, b) => b ? `${Math.round(a / b * 100)}%` : '-';
const 줄 = ['# 모델 비교 — 공식 페이지 8곳', ''];
const 요약 = [];

for (const 모델 of 모델들) {
  const { 만든날, 보고 } = JSON.parse(fs.readFileSync(`data/수정안/${모델}.json`, 'utf8'));
  const 합 = { AI칸수: 0, CSV칸수: 0, 일치칸수: 0, 요금비교: 0, 요금일치: 0, 걸린초: 0, 추정비용달러: 0 };
  줄.push(`## ${보고[0].모델} (비교한 날 ${만든날})`, '', '| 수영장 | 페이지 상태 | AI가 읽은 칸 | CSV 칸 | 겹침 | CSV에 없는데 읽음 | CSV에 있는데 못 읽음 | 요금 일치 | 초 | 추정 $ |', '| --- | --- | ---: | ---: | ---: | ---: | ---: | --- | ---: | ---: |');
  for (const r of 보고) {
    const n = r.숫자;
    if (!r.못읽음) for (const k of ['AI칸수', 'CSV칸수', '일치칸수', '요금비교', '요금일치']) 합[k] += n[k];
    합.걸린초 += n.걸린초; 합.추정비용달러 += n.추정비용달러 ?? 0;
    줄.push(`| ${r.id} ${r.이름} | ${r.못읽음 ? `${r.운영상태}(비교 안 함)` : '운영'} | ${n.AI칸수} | ${r.못읽음 ? '-' : n.CSV칸수} | ${r.못읽음 ? '-' : n.일치칸수} | ${r.못읽음 ? '-' : n.AI칸수 - n.일치칸수} | ${r.못읽음 ? '-' : n.CSV칸수 - n.일치칸수} | ${n.요금비교 ? `${n.요금일치}/${n.요금비교}` : '-'} | ${n.걸린초.toFixed(1)} | ${(n.추정비용달러 ?? 0).toFixed(3)} |`);
  }
  줄.push(`| **합계(운영 중인 곳만)** | | ${합.AI칸수} | ${합.CSV칸수} | ${합.일치칸수} | ${합.AI칸수 - 합.일치칸수} | ${합.CSV칸수 - 합.일치칸수} | ${합.요금일치}/${합.요금비교} | ${합.걸린초.toFixed(1)} | ${합.추정비용달러.toFixed(3)} |`, '');
  요약.push({ 모델: 보고[0].모델, 읽은것중맞음: 퍼센트(합.일치칸수, 합.AI칸수), CSV중찾음: 퍼센트(합.일치칸수, 합.CSV칸수), 요금: `${합.요금일치}/${합.요금비교}`, 초: 합.걸린초.toFixed(1), 비용: 합.추정비용달러.toFixed(3) });
}

줄.splice(2, 0, '> "칸"은 요일 하나 × 회차 하나다(월~금 08:00은 5칸). 기준은 지금 CSV이고, CSV가 틀렸을 수 있어 정답률이 아니라 일치율이다.', '> 요금은 CSV에서 공식 확인된 값만 비교했다(외부 참고값·빈 칸 제외).', '',
  '| 모델 | 읽은 칸 중 CSV와 겹침 | CSV 칸 중 찾음 | 요금 일치 | 8곳 걸린 시간(초) | 8곳 추정 비용($) |', '| --- | ---: | ---: | --- | ---: | ---: |',
  ...요약.map(s => `| ${s.모델} | ${s.읽은것중맞음} | ${s.CSV중찾음} | ${s.요금} | ${s.초} | ${s.비용} |`), '');

fs.mkdirSync('data/비교', { recursive: true });
fs.writeFileSync('data/비교/결과.md', 줄.join('\n') + '\n');
console.table(요약);
